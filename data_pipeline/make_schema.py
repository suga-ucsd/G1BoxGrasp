"""Writes the Observer Custom Schema (YAML) for the G1 box task from the robot MJCF and the scene: every name is
checked against the MJCF, and the free boxes are found in the scene, so the recording is never refused.

    python make_schema.py --mjcf .../g1_three_fingers.xml --scene .../Main.hscene.auto --out schema/g1_act_schema.yaml
"""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from common import IMU, POST_RESET, UPPER_JOINTS, q, scene_boxes, u


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mjcf", required=True, help="robot MJCF (g1_three_fingers.xml)")
    ap.add_argument("--scene", required=True, help="scene .hscene / .hscene.auto, for the free boxes")
    ap.add_argument("--out", default="schema/g1_act_schema.yaml")
    a = ap.parse_args()

    # Names the MJCF really has
    root = ET.parse(a.mjcf).getroot()
    joints = {j.get("name") for j in root.iter("joint")}
    actuators = {e.get("name") for e in root.iter() if e.get("joint") and e.get("name")}  # <position>/<motor> in <actuator>
    sensors = {e.get("name") for e in root.iter() if e.get("site") and e.tag in ("gyro", "accelerometer") and e.get("name")}
    missing = [j for j in UPPER_JOINTS if j not in joints or j not in actuators] + [s for s in IMU.values() if s not in sensors]
    if missing:
        print(f"not in {a.mjcf}: {missing}", file=sys.stderr)
        return 1
    boxes = scene_boxes(a.scene)
    if not boxes:
        print(f"no free boxes in {a.scene}", file=sys.stderr)
        return 1

    # One column per quantity: proprioception, IMU, upper-body ctrl, then privileged poses and the reset flag
    lines = ["# Observer Custom Schema for the G1 box task (generated by make_schema.py; do not edit by hand)", "version: 1", "columns:"]
    lines += ["  # proprioception: observation.state"]
    lines += [f"  - {{ name: {q(j)}, source: mujoco.qpos, select: {{ joint: {j} }}, unit: rad }}" for j in UPPER_JOINTS]
    lines += [f"  - {{ name: {k}, source: mujoco.sensor, select: {{ sensor: {s} }}, shape: 3 }}" for k, s in IMU.items()]
    lines += ["  # upper-body actuator commands: the first 31 action values"]
    lines += [f"  - {{ name: {u(j)}, source: mujoco.ctrl, select: {{ actuator: {j} }}, unit: rad }}" for j in UPPER_JOINTS]
    lines += ["  # privileged: analysis and success labels only, never policy input"]
    lines += ["  - { name: pose.pelvis, source: mujoco.body_pose, select: { body: pelvis } }"]
    lines += [f"  - {{ name: pose.box.{tag}, source: mujoco.body_pose, select: {{ body: {body} }} }}" for tag, body in boxes]
    lines += [f"  - {{ name: {POST_RESET}, source: engine.frame_flag, select: {{ flag: PostReset }} }}"]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(UPPER_JOINTS)} joints, {len(IMU)} IMU sensors, {len(UPPER_JOINTS)} actuators, {len(boxes)} boxes ({', '.join(t for t, _ in boxes)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
